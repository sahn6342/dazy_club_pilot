import { useEffect, useState } from "react";
import { getVenueInfo } from "../lib/api";

export function WhatsappFab() {
  const [href, setHref] = useState("");

  useEffect(() => {
    getVenueInfo()
      .then((v) => {
        const phone = (v.whatsapp_phone ?? "").replace(/\D/g, "");
        const msg   = v.whatsapp_message ?? "Hello! I am interested.";
        if (phone) setHref(`https://wa.me/${phone}?text=${encodeURIComponent(msg)}`);
      })
      .catch(() => {});
  }, []);

  if (!href) return null;

  return (
    <a
      className="whatsapp-fab"
      href={href}
      target="_blank"
      rel="noopener noreferrer"
      aria-label="Chat on WhatsApp"
    >
      <svg viewBox="0 0 32 32" aria-hidden="true">
        <path d="M16 0C7.163 0 0 7.163 0 16c0 2.82.736 5.47 2.027 7.77L0 32l8.43-2.01A15.94 15.94 0 0 0 16 32c8.837 0 16-7.163 16-16S24.837 0 16 0zm0 29.333a13.27 13.27 0 0 1-6.77-1.852l-.486-.29-5.003 1.194 1.216-4.872-.317-.5A13.27 13.27 0 0 1 2.667 16C2.667 8.636 8.636 2.667 16 2.667S29.333 8.636 29.333 16 23.364 29.333 16 29.333zm7.27-9.908c-.398-.2-2.354-1.162-2.72-1.294-.365-.133-.63-.2-.896.2-.265.398-1.028 1.294-1.26 1.56-.232.266-.464.3-.862.1-.398-.2-1.68-.62-3.2-1.975-1.183-1.055-1.982-2.357-2.214-2.755-.232-.398-.025-.613.174-.812.179-.178.398-.465.597-.697.2-.232.266-.398.398-.664.133-.266.067-.498-.033-.697-.1-.2-.896-2.16-1.228-2.957-.323-.776-.65-.67-.896-.683l-.764-.013c-.266 0-.697.1-1.062.498-.365.398-1.393 1.361-1.393 3.32 0 1.96 1.426 3.855 1.625 4.12.2.266 2.806 4.283 6.798 6.008.95.41 1.692.655 2.27.838.954.303 1.822.26 2.508.158.765-.114 2.354-.962 2.687-1.892.333-.93.333-1.727.233-1.892-.1-.166-.365-.266-.763-.465z" />
      </svg>
    </a>
  );
}
